    private void CalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalculateActionPerformed
        // TODO add your handling code here:
        String c1 = (String) Course1Grade.getSelectedItem();
        double g1 = Double.parseDouble(c1);
        String c2 = (String) Course2Grade.getSelectedItem();
        double g2 = Double.parseDouble(c2);
        String c3 = (String) Course3Grade.getSelectedItem();
        double g3 = Double.parseDouble(c3);
        String c4 = (String) Course4Grade.getSelectedItem();
        double g4 = Double.parseDouble(c4);
        String c5 = (String) Course5Grade.getSelectedItem();
        double g5 = Double.parseDouble(c5);
        
        double cgpaGenerator = (g1 + g2 + g3 + g4 +g5) / 5;
        String cgpaString = Double.toString(cgpaGenerator);
        
        CalculateCGPA.setText(cgpaString);
    }//GEN-LAST:event_CalculateActionPerformed

