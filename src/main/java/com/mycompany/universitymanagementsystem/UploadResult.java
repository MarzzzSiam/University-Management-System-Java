    public static void writeToFile(String content) {
        try {
            BufferedWriter writer = new BufferedWriter(new FileWriter("Result.txt", true)); // 'true' parameter to append to file
            writer.write(content);
            writer.newLine(); // Add newline after each content
            writer.close();
        } catch (IOException e) {
            System.err.println("An error occurred while writing to the file: " + e.getMessage());
        }
    }
    
